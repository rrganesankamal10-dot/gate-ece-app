bool topicIdsMatch(String id1, String id2) {
  if (id1 == id2) return true;
  final s1 = id1.toLowerCase();
  final s2 = id2.toLowerCase();
  if ((s1 == 'edc' || s1 == 'devices') && (s2 == 'edc' || s2 == 'devices')) return true;
  if ((s1 == 'communication' || s1 == 'communications') && (s2 == 'communication' || s2 == 'communications')) return true;
  if ((s1 == 'em' || s1 == 'electromagnetics') && (s2 == 'em' || s2 == 'electromagnetics')) return true;
  if ((s1 == 'maths' || s1 == 'math') && (s2 == 'maths' || s2 == 'math')) return true;
  return false;
}

